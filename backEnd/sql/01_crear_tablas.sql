-- 1) Borrar tablas si existen, en orden inverso a las dependencias
DROP TABLE IF EXISTS detalle_atencion CASCADE CONSTRAINTS PURGE;
DROP TABLE IF EXISTS atenciones       CASCADE CONSTRAINTS PURGE;
DROP TABLE IF EXISTS servicios        CASCADE CONSTRAINTS PURGE;
DROP TABLE IF EXISTS mascotas         CASCADE CONSTRAINTS PURGE;
DROP TABLE IF EXISTS duenos           CASCADE CONSTRAINTS PURGE;

-- 2) DUENOS (tabla maestra)
CREATE TABLE duenos (
    id              NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1 NOCACHE),
    rut             VARCHAR2(12)  NOT NULL,
    nombre          VARCHAR2(100) NOT NULL,
    telefono        VARCHAR2(20)  NOT NULL,
    email           VARCHAR2(120) NOT NULL,
    comuna          VARCHAR2(60)  NOT NULL,
    fecha_registro  TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    CONSTRAINT pk_duenos       PRIMARY KEY (id),
    CONSTRAINT uq_duenos_rut   UNIQUE (rut),
    CONSTRAINT uq_duenos_email UNIQUE (email),
    CONSTRAINT ck_duenos_email CHECK (INSTR(email, '@') > 1)
);

-- 3) MASCOTAS (tabla maestra, depende de duenos)
CREATE TABLE mascotas (
    id                NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1 NOCACHE),
    dueno_id          NUMBER        NOT NULL,
    nombre            VARCHAR2(60)  NOT NULL,
    especie           VARCHAR2(20)  NOT NULL,
    raza              VARCHAR2(60),
    sexo              VARCHAR2(1)   NOT NULL,
    fecha_nacimiento  DATE,
    CONSTRAINT pk_mascotas         PRIMARY KEY (id),
    CONSTRAINT fk_mascotas_dueno   FOREIGN KEY (dueno_id) REFERENCES duenos (id),
    CONSTRAINT ck_mascotas_especie CHECK (especie IN ('perro','gato','ave','conejo','reptil','otro')),
    CONSTRAINT ck_mascotas_sexo    CHECK (sexo IN ('M','H'))
);
CREATE INDEX idx_mascotas_dueno ON mascotas (dueno_id);

-- 4) SERVICIOS (tabla maestra)
CREATE TABLE servicios (
    id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1 NOCACHE),
    codigo      VARCHAR2(10)   NOT NULL,
    nombre      VARCHAR2(100)  NOT NULL,
    descripcion CLOB,
    precio      NUMBER(10,2)   NOT NULL,
    activo      NUMBER(1)      DEFAULT 1 NOT NULL,
    CONSTRAINT pk_servicios         PRIMARY KEY (id),
    CONSTRAINT uq_servicios_codigo  UNIQUE (codigo),
    CONSTRAINT uq_servicios_nombre  UNIQUE (nombre),
    CONSTRAINT ck_servicios_precio  CHECK (precio >= 0),
    CONSTRAINT ck_servicios_activo  CHECK (activo IN (0,1))
);

-- 5) ATENCIONES (entidad principal, con estados)
CREATE TABLE atenciones (
    id              NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1 NOCACHE),
    mascota_id      NUMBER         NOT NULL,
    fecha           TIMESTAMP      NOT NULL,
    motivo          VARCHAR2(200)  NOT NULL,
    total           NUMBER(10,2)   DEFAULT 0 NOT NULL,
    estado          VARCHAR2(12)   DEFAULT 'agendada' NOT NULL,
    fecha_creacion  TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    CONSTRAINT pk_atenciones          PRIMARY KEY (id),
    CONSTRAINT fk_atenciones_mascota  FOREIGN KEY (mascota_id) REFERENCES mascotas (id),
    CONSTRAINT ck_atenciones_total    CHECK (total >= 0),
    CONSTRAINT ck_atenciones_estado   CHECK (estado IN ('agendada','realizada','pagada','cancelada'))
);
CREATE INDEX idx_atenciones_mascota ON atenciones (mascota_id);
CREATE INDEX idx_atenciones_fecha   ON atenciones (fecha);

-- 6) DETALLE_ATENCION (detalle con clave primaria compuesta y columna virtual)
CREATE TABLE detalle_atencion (
    atencion_id      NUMBER        NOT NULL,
    servicio_id      NUMBER        NOT NULL,
    cantidad         NUMBER(5)     NOT NULL,
    precio_unitario  NUMBER(10,2)  NOT NULL,
    subtotal         NUMBER(12,2)  GENERATED ALWAYS AS (cantidad * precio_unitario) VIRTUAL,
    CONSTRAINT pk_detalle_atencion   PRIMARY KEY (atencion_id, servicio_id),
    CONSTRAINT fk_detalle_atencion   FOREIGN KEY (atencion_id) REFERENCES atenciones (id) ON DELETE CASCADE,
    CONSTRAINT fk_detalle_servicio   FOREIGN KEY (servicio_id) REFERENCES servicios (id),
    CONSTRAINT ck_detatencion_cantidad CHECK (cantidad > 0),
    CONSTRAINT ck_detatencion_precio   CHECK (precio_unitario >= 0)
);
CREATE INDEX idx_detalle_atencion ON detalle_atencion (atencion_id);
CREATE INDEX idx_detalle_servicio ON detalle_atencion (servicio_id);

-- 7) Verificación: deben aparecer las 5 tablas
SELECT table_name FROM user_tables
 WHERE table_name IN ('DUENOS','MASCOTAS','SERVICIOS','ATENCIONES','DETALLE_ATENCION')
 ORDER BY table_name;
